const MAX_DISPLAYED_CODES = 10;

const PROVENANCE_METHOD_LABELS: { [method: string]: string } = {
    "authoritative-import": "Authoritative source",
    harvested: "Harvested",
    inferred: "Inferred",
    manual: "Manual / custodian",
    "agent-generated": "Agent-generated"
};

const REVIEW_STATUS_LABELS: { [status: string]: string } = {
    unreviewed: "Unreviewed",
    reviewed: "Reviewed",
    "custodian-approved": "Custodian-approved",
    rejected: "Rejected"
};

export function describeProvenance(
    provenance?: DataDictionaryProvenance
): string {
    if (!provenance) {
        return "Unknown origin";
    }
    const parts: string[] = [];
    if (provenance.method) {
        parts.push(
            PROVENANCE_METHOD_LABELS[provenance.method] ?? provenance.method
        );
    }
    if (provenance.reviewStatus) {
        parts.push(
            REVIEW_STATUS_LABELS[provenance.reviewStatus] ??
                provenance.reviewStatus
        );
    }
    return parts.length ? parts.join(" · ") : "Unknown origin";
}

function formatBytes(bytes: number): string {
    if (bytes < 1024) {
        return `${bytes} bytes`;
    }
    if (bytes < 1024 * 1024) {
        return `${Math.round(bytes / 1024)} KB`;
    }
    return `${Math.round(bytes / (1024 * 1024))} MB`;
}

export function describeSample(
    provenance?: DataDictionaryProvenance
): string | undefined {
    const sample = provenance?.sample;
    if (!sample) {
        return undefined;
    }
    const extent: string[] = [];
    if (typeof sample.rows === "number") {
        extent.push(`${sample.rows} rows`);
    }
    if (typeof sample.bytes === "number") {
        extent.push(formatBytes(sample.bytes));
    }
    if (!extent.length) {
        return undefined;
    }
    return `Inferred from a sample of ${extent.join(
        " / "
    )}; may not be complete.`;
}

function isUrl(value: unknown): value is string {
    return typeof value === "string" && /^https?:\/\//i.test(value);
}

function displayValue(value: unknown): string {
    if (typeof value === "string") {
        return value;
    }
    try {
        return JSON.stringify(value);
    } catch (e) {
        return String(value);
    }
}

function toSearchText(field: DataDictionaryField): string {
    return [
        field.name,
        field.title,
        field.path,
        field.description,
        field.semanticConcept,
        field.unit,
        field.type,
        field.format,
        field.sourceType,
        ...(field.aliases ?? [])
    ]
        .filter((value) => typeof value === "string")
        .join("\n")
        .toLowerCase();
}

/** Whether a field matches a free-text search query (case-insensitive). */
export function fieldMatchesQuery(
    field: DataDictionaryField,
    query: string
): boolean {
    const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
    if (!terms.length) {
        return true;
    }
    const text = toSearchText(field);
    return terms.every((term) => text.indexOf(term) !== -1);
}

function getDepth(path: string): number {
    return isValidFieldPath(path) ? getFieldPathDepth(path) : 0;
}

const ProvenanceBadge: FunctionComponent<{
    provenance?: DataDictionaryProvenance;
    label?: string;
}> = ({ provenance, label }) => {
    const advisory = isAdvisoryProvenance(provenance);
    const rejected = provenance?.reviewStatus === "rejected";
    const className = [
        "data-dictionary__provenance",
        advisory ? "data-dictionary__provenance--advisory" : "",
        rejected ? "data-dictionary__provenance--rejected" : ""
    ]
        .filter(Boolean)
        .join(" ");
    const titleParts = [
        provenance?.generator ? `Generated by ${provenance.generator}` : "",
        provenance?.generatedAt ? `at ${provenance.generatedAt}` : "",
        provenance?.reviewedBy ? `Reviewed by ${provenance.reviewedBy}` : "",
        describeSample(provenance) ?? "",
        provenance?.note ?? ""
    ].filter(Boolean);
    return (
        <span
            className={className}
            title={titleParts.length ? titleParts.join(" ") : undefined}
        >
            {label ? `${label}: ` : ""}
            {describeProvenance(provenance)}
        </span>
    );
};

const FieldConstraints: FunctionComponent<{ field: DataDictionaryField }> = ({
    field
}) => {
    const items: React.ReactNode[] = [];
    const domain = field.valueDomain;
    if (domain?.values?.length) {
        const shown = domain.values.slice(0, MAX_DISPLAYED_CODES);
        items.push(
            <span key="codes">
                Codes:{" "}
                {shown.map((item, idx) => (
                    <React.Fragment key={idx}>
                        {idx ? ", " : ""}
                        <code>{displayValue(item.value)}</code>
                        {item.label ? ` = ${item.label}` : ""}
                    </React.Fragment>
                ))}
                {domain.values.length > shown.length
                    ? ` (+${domain.values.length - shown.length} more)`
                    : ""}
            </span>
        );
    }
    if (isUrl(domain?.uri)) {
        items.push(
            <span key="codelist-uri">
                Code list:{" "}
                <a href={domain!.uri} target="_blank" rel="noopener noreferrer">
                    {domain!.name || domain!.uri}
                </a>
            </span>
        );
    } else if (domain?.uri) {
        items.push(<span key="codelist-uri">Code list: {domain.uri}</span>);
    }
    if (domain?.minimum !== undefined || domain?.maximum !== undefined) {
        items.push(
            <span key="range">
                Range: {displayValue(domain?.minimum ?? "…")} –{" "}
                {displayValue(domain?.maximum ?? "…")}
            </span>
        );
    }
    if (Array.isArray(field.enum) && field.enum.length) {
        const shown = field.enum.slice(0, MAX_DISPLAYED_CODES);
        items.push(
            <span key="enum">
                Allowed values:{" "}
                {shown.map((value, idx) => (
                    <React.Fragment key={idx}>
                        {idx ? ", " : ""}
                        <code>{displayValue(value)}</code>
                    </React.Fragment>
                ))}
                {field.enum.length > shown.length
                    ? ` (+${field.enum.length - shown.length} more)`
                    : ""}
            </span>
        );
    }
    if (field.minimum !== undefined || field.maximum !== undefined) {
        items.push(
            <span key="min-max">
                Values: {displayValue(field.minimum ?? "…")} –{" "}
                {displayValue(field.maximum ?? "…")}
            </span>
        );
    }
    if (field.minLength !== undefined || field.maxLength !== undefined) {
        items.push(
            <span key="length">
                Length: {field.minLength ?? 0} – {field.maxLength ?? "…"}
            </span>
        );
    }
    if (field.pattern) {
        items.push(
            <span key="pattern">
                Pattern: <code>{field.pattern}</code>
            </span>
        );
    }
    if (Array.isArray(field.missingValues) && field.missingValues.length) {
        items.push(
            <span key="missing">
                Missing values:{" "}
                {field.missingValues.map((value, idx) => (
                    <React.Fragment key={idx}>
                        {idx ? ", " : ""}
                        <code>{displayValue(value)}</code>
                    </React.Fragment>
                ))}
            </span>
        );
    }
    if (field.dimensions?.length) {
        items.push(
            <span key="dims">Dimensions: {field.dimensions.join(" × ")}</span>
        );
    }
    if (!items.length) {
        return null;
    }
    return (
        <ul className="data-dictionary__constraints">
            {items.map((item, idx) => (
                <li key={idx}>{item}</li>
            ))}
        </ul>
    );
};

function describeRequired(field: DataDictionaryField): string {
    const parts: string[] = [];
    if (field.required === true) {
        parts.push("Required");
    } else if (field.required === false) {
        parts.push("Optional");
    }
    if (field.nullable === true) {
        parts.push("Nullable");
    } else if (field.nullable === false) {
        parts.push("Not null");
    }
    return parts.length ? parts.join(", ") : "Unknown";
}

const FieldRow: FunctionComponent<{
    dictionary: DataDictionaryAspect;
    entity: DataDictionaryEntity;
    field: DataDictionaryField;
    isPrimaryKey: boolean;
}> = ({ dictionary, entity, field, isPrimaryKey }) => {
    const depth = getDepth(field.path);
    const provenance = getEffectiveProvenance(dictionary, [entity, field]);
    const propertyOverrides = field.propertyProvenance
        ? Object.keys(field.propertyProvenance)
        : [];
    return (
        <tr
            className="data-dictionary__field"
            data-field-path={field.path}
            data-depth={depth}
        >
            <td className="data-dictionary__field-name">
                <div style={{ paddingLeft: `${depth * 16}px` }}>
                    <strong>{field.title || field.name}</strong>
                    {field.title && field.title !== field.name ? (
                        <span className="data-dictionary__muted">
                            {" "}
                            ({field.name})
                        </span>
                    ) : null}
                    {field.path !== field.name ? (
                        <div>
                            <code
                                className="data-dictionary__path"
                                title="Stable field path"
                            >
                                {field.path}
                            </code>
                        </div>
                    ) : null}
                    {isPrimaryKey || field.roles?.length ? (
                        <div className="data-dictionary__tags">
                            {isPrimaryKey ? (
                                <span className="data-dictionary__tag">
                                    primary key
                                </span>
                            ) : null}
                            {(field.roles ?? []).map((role) => (
                                <span
                                    key={role}
                                    className="data-dictionary__tag"
                                >
                                    {role}
                                </span>
                            ))}
                        </div>
                    ) : null}
                </div>
            </td>
            <td className="data-dictionary__field-type">
                <code>{field.type}</code>
                {field.format ? (
                    <span className="data-dictionary__muted">
                        {" "}
                        ({field.format})
                    </span>
                ) : null}
                {field.sourceType ? (
                    <div
                        className="data-dictionary__muted"
                        title="Native source type"
                    >
                        Source: <code>{field.sourceType}</code>
                    </div>
                ) : null}
            </td>
            <td className="data-dictionary__field-description">
                {field.description ? <div>{field.description}</div> : null}
                {field.semanticConcept ? (
                    <div className="data-dictionary__concept">
                        Concept:{" "}
                        {isUrl(field.semanticConcept) ? (
                            <a
                                href={field.semanticConcept}
                                target="_blank"
                                rel="noopener noreferrer"
                            >
                                {field.semanticConcept}
                            </a>
                        ) : (
                            <code>{field.semanticConcept}</code>
                        )}
                    </div>
                ) : null}
                <FieldConstraints field={field} />
            </td>
            <td className="data-dictionary__field-unit">
                {field.unit ? (
                    <span
                        title={
                            field.unitSystem
                                ? `Unit system: ${field.unitSystem}`
                                : undefined
                        }
                    >
                        {field.unit}
                    </span>
                ) : (
                    <span className="data-dictionary__muted">—</span>
                )}
            </td>
            <td className="data-dictionary__field-required">
                {describeRequired(field)}
            </td>
            <td className="data-dictionary__field-provenance">
                <ProvenanceBadge provenance={provenance} />
                {propertyOverrides.map((property) => (
                    <div key={property}>
                        <ProvenanceBadge
                            label={property}
                            provenance={getEffectiveProvenance(
                                dictionary,
                                [entity, field],
                                property
                            )}
                        />
                    </div>
                ))}
                {field.conflicts?.length ? (
                    <div>
                        <span
                            className="data-dictionary__provenance data-dictionary__provenance--conflict"
                            title={field.conflicts
                                .map(
                                    (conflict) =>
                                        `${conflict.property ?? "field"}: ${
                                            conflict.reason ?? "changed"
                                        }`
                                )
                                .join("; ")}
                        >
                            Needs review: source changed
                        </span>
                    </div>
                ) : null}
            </td>
        </tr>
    );
};

function getEntityName(
    dictionary: DataDictionaryAspect,
    entityId: string
): string {
    return (
        dictionary.entities.find((entity) => entity.id === entityId)?.name ??
        entityId
    );
}

const EntityRelationships: FunctionComponent<{
    dictionary: DataDictionaryAspect;
    entity: DataDictionaryEntity;
}> = ({ dictionary, entity }) => {
    const relationships = (dictionary.relationships ?? []).filter(
        (rel: DataDictionaryRelationship) =>
            rel.source.entity === entity.id || rel.target.entity === entity.id
    );
    if (!relationships.length) {
        return null;
    }
    return (
        <div className="data-dictionary__relationships">
            <span>Declared relationships:</span>
            <ul>
                {relationships.map((rel) => (
                    <li key={rel.id}>
                        {getEntityName(dictionary, rel.source.entity)}{" "}
                        <code>({rel.source.fields.join(", ")})</code> →{" "}
                        {getEntityName(dictionary, rel.target.entity)}{" "}
                        <code>({rel.target.fields.join(", ")})</code>{" "}
                        <span className="data-dictionary__muted">
                            ({rel.type || "foreign-key"})
                        </span>
                        {rel.description ? ` — ${rel.description}` : null}
                    </li>
                ))}
            </ul>
        </div>
    );
};

const EntityDetails: FunctionComponent<{
    dictionary: DataDictionaryAspect;
    entity: DataDictionaryEntity;
    fields: DataDictionaryField[];
    query: string;
}> = ({ dictionary, entity, fields, query }) => {
    const primaryKey = entity.primaryKey ?? [];
    const entityProvenance = entity.provenance
        ? getEffectiveProvenance(dictionary, [entity])
        : undefined;
    return (
        <div
            className="data-dictionary__entity"
            data-entity-id={entity.id}
            role="tabpanel"
        >
            <h4 className="data-dictionary__entity-name">
                {entity.name}
                {entity.role ? (
                    <span className="data-dictionary__tag">{entity.role}</span>
                ) : null}
            </h4>
            {entity.description ? <p>{entity.description}</p> : null}
            <ul className="data-dictionary__entity-meta">
                {entityProvenance ? (
                    <li>
                        <ProvenanceBadge provenance={entityProvenance} />
                    </li>
                ) : null}
                {primaryKey.length ? (
                    <li>
                        Primary key: <code>{primaryKey.join(", ")}</code>
                    </li>
                ) : null}
                {entity.geometry ? (
                    <li>
                        Geometry:{" "}
                        {[
                            entity.geometry.type,
                            entity.geometry.crs
                                ? `(${entity.geometry.crs})`
                                : undefined
                        ]
                            .filter(Boolean)
                            .join(" ") || "yes"}
                        {entity.geometry.fieldPath ? (
                            <>
                                {" "}
                                — field <code>{entity.geometry.fieldPath}</code>
                            </>
                        ) : null}
                    </li>
                ) : null}
                {entity.dimensions?.length ? (
                    <li>
                        Dimensions:{" "}
                        {entity.dimensions.map((dim, idx) => (
                            <React.Fragment key={dim.id}>
                                {idx ? ", " : ""}
                                <code>{dim.id}</code>
                                {dim.name && dim.name !== dim.id
                                    ? ` (${dim.name})`
                                    : ""}
                                {typeof dim.size === "number"
                                    ? ` [${dim.size}${
                                          dim.unlimited ? ", unlimited" : ""
                                      }]`
                                    : dim.unlimited
                                    ? " [unlimited]"
                                    : ""}
                            </React.Fragment>
                        ))}
                    </li>
                ) : null}
            </ul>
            <EntityRelationships dictionary={dictionary} entity={entity} />
            {fields.length ? (
                <div className="data-dictionary__table-wrapper">
                    <table className="data-dictionary__table">
                        <caption className="sr-only">
                            Fields of {entity.name}
                        </caption>
                        <thead>
                            <tr>
                                <th scope="col">Field</th>
                                <th scope="col">Type</th>
                                <th scope="col">Description</th>
                                <th scope="col">Unit</th>
                                <th scope="col">Required</th>
                                <th scope="col">Provenance</th>
                            </tr>
                        </thead>
                        <tbody>
                            {fields.map((field) => (
                                <FieldRow
                                    key={field.path}
                                    dictionary={dictionary}
                                    entity={entity}
                                    field={field}
                                    isPrimaryKey={
                                        primaryKey.indexOf(field.path) !== -1
                                    }
                                />
                            ))}
                        </tbody>
                    </table>
                </div>
            ) : (
                <p className="data-dictionary__empty">
                    {query.trim()
                        ? `No fields match "${query.trim()}".`
                        : "No fields are described for this entity."}
                </p>
            )}
        </div>
    );
};

const DictionarySource: FunctionComponent<{
    dictionary: DataDictionaryAspect;
}> = ({ dictionary }) => {
    const source = dictionary.source;
    const sampleNote = describeSample(dictionary.provenance);
    return (
        <div className="data-dictionary__source">
            <div>
                <ProvenanceBadge provenance={dictionary.provenance} />
                {source?.type ? (
                    <span className="data-dictionary__muted">
                        {" "}
                        from <code>{source.type}</code>
                    </span>
                ) : null}
                {source?.retrievedAt ? (
                    <span className="data-dictionary__muted">
                        {" "}
                        (retrieved {source.retrievedAt})
                    </span>
                ) : null}
            </div>
            {sampleNote ? (
                <div className="data-dictionary__muted">{sampleNote}</div>
            ) : null}
            {isUrl(source?.url) || isUrl(source?.documentationUrl) ? (
                <div className="data-dictionary__source-links">
                    {isUrl(source?.url) ? (
                        <a
                            href={source!.url}
                            target="_blank"
                            rel="noopener noreferrer"
                        >
                            Native schema / specification
                        </a>
                    ) : null}
                    {isUrl(source?.documentationUrl) ? (
                        <a
                            href={source!.documentationUrl}
                            target="_blank"
                            rel="noopener noreferrer"
                        >
                            Documentation
                        </a>
                    ) : null}
                </div>
            ) : null}
        </div>
    );
};

/**
 * Read-only "Structure" section rendering the `data-dictionary` aspect of a
 * distribution: entity selection, a searchable field table with stable paths,
 * types, descriptions, units, requiredness, semantic concepts and provenance.
 */
const DataDictionarySection: FunctionComponent<{
    dataDictionary: DataDictionaryAspect;
}> = ({ dataDictionary }) => {
    const entities = dataDictionary.entities;
    const [selectedEntityId, setSelectedEntityId] = useState<string>(
        entities[0]?.id
    );
    const [query, setQuery] = useState<string>("");

    const matchedFields = useMemo(() => {
        const result: { [entityId: string]: DataDictionaryField[] } = {};
        entities.forEach((entity) => {
            result[entity.id] = entity.fields.filter((field) =>
                fieldMatchesQuery(field, query)
            );
        });
        return result;
    }, [entities, query]);

    const selectedEntity =
        entities.find((entity) => entity.id === selectedEntityId) ??
        entities[0];
    const totalFields = entities.reduce(
        (total, entity) => total + entity.fields.length,
        0
    );
    const isSearching = !!query.trim();

    return (
        <section
            className="data-dictionary"
            aria-labelledby="data-dictionary-heading"
        >
            <h3 className="section-heading" id="data-dictionary-heading">
                Structure
            </h3>
            <p className="data-dictionary__summary">
                Data dictionary: {entities.length}{" "}
                {entities.length === 1 ? "entity" : "entities"}, {totalFields}{" "}
                {totalFields === 1 ? "field" : "fields"}.
            </p>
            <DictionarySource dictionary={dataDictionary} />
            {!entities.length ? (
                <p className="data-dictionary__empty">
                    No field-level structure is described for this distribution.
                </p>
            ) : (
                <>
                    {totalFields ? (
                        <div className="data-dictionary__search">
                            <input
                                type="search"
                                className="au-text-input"
                                placeholder="Search fields by name, path, description, concept or unit"
                                aria-label="Search fields"
                                value={query}
                                onChange={(e) => setQuery(e.target.value)}
                            />
                        </div>
                    ) : null}
                    {entities.length > 1 ? (
                        <div
                            className="data-dictionary__entity-selector"
                            role="tablist"
                            aria-label="Entities"
                        >
                            {entities.map((entity) => {
                                const selected =
                                    entity.id === selectedEntity?.id;
                                const count = isSearching
                                    ? matchedFields[entity.id].length
                                    : entity.fields.length;
                                return (
                                    <button
                                        key={entity.id}
                                        type="button"
                                        role="tab"
                                        aria-selected={selected}
                                        className={`data-dictionary__entity-tab${
                                            selected
                                                ? " data-dictionary__entity-tab--selected"
                                                : ""
                                        }`}
                                        onClick={() =>
                                            setSelectedEntityId(entity.id)
                                        }
                                    >
                                        {entity.name}{" "}
                                        <span className="data-dictionary__count">
                                            {isSearching
                                                ? `${count} match${
                                                      count === 1 ? "" : "es"
                                                  }`
                                                : count}
                                        </span>
                                    </button>
                                );
                            })}
                        </div>
                    ) : null}
                    {selectedEntity ? (
                        <EntityDetails
                            dictionary={dataDictionary}
                            entity={selectedEntity}
                            fields={matchedFields[selectedEntity.id] ?? []}
                            query={query}
                        />
                    ) : null}
                </>
            )}
        </section>
    );
};

export default DataDictionarySection;
